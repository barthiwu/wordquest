# --- Key-parity + placeholder-parity verification against en.json ---
import re

def leaf_keys(d, prefix=""):
    keys = set()
    for k, v in d.items():
        full = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            keys |= leaf_keys(v, full)
        else:
            keys.add(full)
    return keys

def placeholders(d, prefix=""):
    out = {}
    for k, v in d.items():
        full = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            out.update(placeholders(v, full))
        elif isinstance(v, str):
            out[full] = tuple(sorted(re.findall(r"\{\{(\w+)\}\}", v)))
    return out

en_data = json.load(io.open(f"{LOCALES_DIR}/en.json", encoding="utf-8"))
en_keys = leaf_keys({"arcade": en_data["arcade"], "scrambleQuest": en_data["scrambleQuest"], "home": {"arcade": en_data["home"]["arcade"]}})
en_ph = placeholders({"arcade": en_data["arcade"], "scrambleQuest": en_data["scrambleQuest"], "home": {"arcade": en_data["home"]["arcade"]}})

all_ok = True
for lang in LANGS:
    if lang == "en":
        continue
    d = json.load(io.open(f"{LOCALES_DIR}/{lang}.json", encoding="utf-8"))
    sub = {"arcade": d["arcade"], "scrambleQuest": d["scrambleQuest"], "home": {"arcade": d["home"]["arcade"]}}
    keys = leaf_keys(sub)
    ph = placeholders(sub)
    missing = en_keys - keys
    extra = keys - en_keys
    ph_mismatch = {k: (en_ph[k], ph.get(k)) for k in en_ph if ph.get(k) != en_ph[k]}
    if missing or extra or ph_mismatch:
        all_ok = False
        print(f"MISMATCH in {lang}: missing={missing} extra={extra} placeholder_mismatch={ph_mismatch}")

print("ALL_OK" if all_ok else "PARITY_FAILED")
